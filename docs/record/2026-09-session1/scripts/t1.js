const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' }).catch(()=>chromium.launch());
  const p = await b.newPage({ viewport: { width: 1100, height: 900 } });
  const errs=[]; p.on('pageerror', e=>errs.push(e.message)); p.on('console', m=>{if(m.type()==='error')errs.push(m.text())});
  await p.goto('http://localhost:8765/field/index.html');
  await p.evaluate(()=>localStorage.clear()); await p.reload(); await p.waitForTimeout(800);
  const hold=async(k,ms)=>{await p.keyboard.down(k);await p.waitForTimeout(ms);await p.keyboard.up(k);await p.waitForTimeout(120)};
  const enter=async(n)=>{for(let i=0;i<n;i++){await p.keyboard.press('Enter');await p.waitForTimeout(260)}};
  const shot=async(n)=>p.locator('.game-frame').screenshot({path:`s_${n}.png`});
  await hold('ArrowUp',2100); await p.waitForTimeout(400); await shot('01_frag');
  await enter(2); await p.waitForTimeout(1200); await shot('02_world');
  await enter(4); await p.waitForTimeout(300);
  await hold("ArrowUp",330); await shot("03_car_near");
  await enter(1); await p.waitForTimeout(700); await shot('04_car_dialog');
  await enter(14);
  await hold('ArrowRight',2100); await shot('05_road');
  await hold('ArrowUp',900); await p.waitForTimeout(1500); await shot('06_ice');
  await enter(8);
  await hold('ArrowDown',1600); await p.waitForTimeout(800);
  await hold('ArrowDown',600);
  await hold('ArrowRight',2500); await shot('07_right');
  await hold('ArrowDown',1400); await hold('ArrowLeft',700); await shot('08_houtou');
  await enter(1); await p.waitForTimeout(700); await shot('09_houtou_dialog');
  await enter(24); await p.waitForTimeout(1500); await shot('10_back');
  console.log(await p.locator('#inventoryText').innerText().catch(()=>'-'), '|', await p.locator('#progressText').innerText());
  console.log('errors', errs);
  await b.close();
})();
