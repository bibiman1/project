INK = (50, 42, 34); RED = (180, 44, 36); GRN = (40, 120, 60); MUT = (120, 110, 100); BG = (244, 238, 224)
def sheet(w, h, title):
    im = Image.new('RGB', (w, h), BG); d = ImageDraw.Draw(im)
    d.text((24, 16), title, fill=INK, font=f(26)); d.line((24, 52, w - 24, 52), fill=INK, width=2)
    return im, d
def paste(im, src, box, scale=None, crop=None, nearest=True, frame=True):
    s = Image.open(src).convert('RGBA')
    if crop: s = s.crop(crop)
    x0, y0, x1, y1 = box
    k = scale or min((x1 - x0) / s.width, (y1 - y0) / s.height)
    s = s.resize((max(1, int(s.width * k)), max(1, int(s.height * k))), Image.NEAREST if nearest else Image.LANCZOS)
    bgc = Image.new('RGBA', (x1 - x0, y1 - y0), (255, 255, 255, 255))
    bgc.alpha_composite(s, ((x1 - x0 - s.width) // 2, (y1 - y0 - s.height) // 2))
    im.paste(bgc.convert('RGB'), (x0, y0))
    if frame: ImageDraw.Draw(im).rectangle(box, outline=(160, 150, 136))
def cap(d, x, y, t, col=MUT, s=14): d.text((x, y), t, fill=col, font=f(s))
def lines(d, x, y, items, s=16, gap=6, w=None):
    for it in items:
        col = INK
        if it.startswith('!'): col, it = RED, it[1:]
        if it.startswith('+'): col, it = GRN, it[1:]
        if it.startswith('#'):
            d.text((x, y), it[1:], fill=INK, font=f(s + 4)); y += s + 4 + gap + 4; continue
        d.text((x, y), it, fill=col, font=f(s)); y += s + gap
    return y
def mark(d, box, ok):
    x0, y0 = box[0] + 6, box[1] + 4
    d.text((x0, y0), '○ 残す' if ok else '× 直す', fill=GRN if ok else RED, font=f(18))

