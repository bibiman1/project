def block(x, y, items, w=760):
    for it in items:
        col, s = INK, 17
        if it.startswith('#'): d.text((x, y), it[1:], fill=RED, font=f(22)); y += 36; continue
        if it.startswith('+'): col, it = GRN, it[1:]
        d.text((x, y), it, fill=col, font=f(s)); y += 27
    return y
